-- --------------------------------------------------
-- 多表连接查询-客户,订单,订单细节,产品
-- --------------------------------------------------
SELECT 
    客户.客户编号,
    客户.客户名称,
    订单.订单编号,
    订单.订货日期,
    订单.出货日期,
    订单细节.产品编号,
    产品.产品名称,
    产品.产品描述,
    订单细节.时价,
    订单细节.数量,
    ROUND((订单细节.时价 * 订单细节.数量), 2) AS 总价
FROM 
    客户
JOIN 
    订单 ON 客户.客户编号 = 订单.客户编号
JOIN 
    订单细节 ON 订单.订单编号 = 订单细节.订单编号
JOIN 
    产品 ON 订单细节.产品编号 = 产品.产品编号
ORDER BY 订单.订货日期, 订单.订单编号;